create or replace function app_private.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id, role) values (new.id, 'seller') on conflict (id) do nothing;
  insert into public.seller_profiles(user_id,email,business_name,contact_name,phone,whatsapp,address)
  values (
    new.id, coalesce(new.email, ''),
    left(coalesce(new.raw_user_meta_data->>'business_name', ''), 160),
    left(coalesce(new.raw_user_meta_data->>'contact_name', ''), 120),
    left(coalesce(new.raw_user_meta_data->>'phone', ''), 40),
    left(coalesce(new.raw_user_meta_data->>'whatsapp', ''), 40),
    left(coalesce(new.raw_user_meta_data->>'address', ''), 500)
  ) on conflict (user_id) do nothing;
  return new;
end;
$$;
revoke all on function app_private.handle_new_user() from public, anon, authenticated;
drop trigger if exists on_auth_user_created_exopets on auth.users;
create trigger on_auth_user_created_exopets after insert on auth.users
for each row execute function app_private.handle_new_user();

