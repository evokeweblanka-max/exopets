-- EXOPETS multi-seller marketplace schema.
-- The admin bridge secret hash is installed separately and is never committed.

create extension if not exists pgcrypto with schema extensions;
create schema if not exists app_private;
revoke all on schema app_private from public, anon, authenticated;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'seller' check (role in ('seller','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.seller_profiles (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  email text not null,
  business_name text not null default '',
  contact_name text not null default '',
  phone text not null default '',
  whatsapp text not null default '',
  address text not null default '',
  bio text not null default '',
  status text not null default 'pending' check (status in ('pending','approved','rejected','suspended')),
  rejection_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.marketplace_products (
  id uuid primary key default gen_random_uuid(),
  seller_id uuid not null references public.seller_profiles(user_id) on delete cascade,
  name text not null check (char_length(name) between 2 and 120),
  slug text not null,
  category text not null default 'Bird care',
  description text not null default '',
  price numeric(12,2) not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  availability_note text not null default 'Contact seller for availability',
  status text not null default 'draft' check (status in ('draft','pending','approved','rejected')),
  is_active boolean not null default true,
  rejection_reason text,
  submitted_at timestamptz,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (seller_id, slug)
);

create table if not exists public.marketplace_product_images (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.marketplace_products(id) on delete cascade,
  seller_id uuid not null references public.seller_profiles(user_id) on delete cascade,
  storage_path text not null unique,
  alt_text text not null default '',
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.marketplace_moderation_events (
  id bigint generated by default as identity primary key,
  actor text not null,
  entity_type text not null check (entity_type in ('seller','product')),
  entity_id uuid not null,
  action text not null,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists app_private.settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

